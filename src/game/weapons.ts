export interface ScopeZoomProfile {
  level: number;
  label: string;
  cameraScale: number;
  lookAheadPx: number;
  laserLengthPx: number;
}

export const SCOPE_ZOOM_PROFILES: Record<number, ScopeZoomProfile> = {
  1: { level: 1, label: '1X', cameraScale: 1.15, lookAheadPx: 65, laserLengthPx: 140 },
  2: { level: 2, label: '2X', cameraScale: 1.0, lookAheadPx: 135, laserLengthPx: 340 },
  3: { level: 3, label: '3X', cameraScale: 0.84, lookAheadPx: 215, laserLengthPx: 580 },
  4: { level: 4, label: '4X', cameraScale: 0.73, lookAheadPx: 285, laserLengthPx: 820 },
  5: { level: 5, label: '5X', cameraScale: 0.62, lookAheadPx: 365, laserLengthPx: 1250 },
};

export function getScopeZoomProfile(level: number): ScopeZoomProfile {
  const clamped = Math.max(1, Math.min(5, Math.round(level)));
  return SCOPE_ZOOM_PROFILES[clamped] ?? SCOPE_ZOOM_PROFILES[1];
}

export function cycleWeaponScopeZoom(currentLevel: number, weaponMaxZoom: number): number {
  const maxZ = Math.max(2, Math.min(5, weaponMaxZoom));
  if (currentLevel >= maxZ) return 1;
  if (maxZ === 5) {
    if (currentLevel === 1) return 3;
    return 5;
  }
  if (maxZ === 4) {
    if (currentLevel === 1) return 2;
    return 4;
  }
  return currentLevel + 1;
}

